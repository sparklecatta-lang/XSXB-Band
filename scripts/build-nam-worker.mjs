// Generates public/nam/nam-worker.js from the vendored worklet: the same Emscripten glue and wasm,
// driven from a dedicated Worker so several NAM captures can render in parallel (one per core).
// Re-run after updating public/nam/nam-worklet.js.
import { readFile, writeFile } from 'node:fs/promises';
const root = new URL('../public/nam/', import.meta.url);
const worklet = await readFile(new URL('nam-worklet.js', root), 'utf8');
const end = worklet.indexOf('return Module}');
if (!worklet.startsWith('async function createNamEngine') || end < 0) throw Error('Unexpected nam-worklet.js layout');
const glue = worklet.slice(0, end + 'return Module}'.length);
const worker = `// GENERATED by scripts/build-nam-worker.mjs from nam-worklet.js (neural-amp-modeler-wasm, MIT).
// Emscripten glue for NeuralAmpModelerCore (MIT) follows unchanged.
${glue}

// --- Klein Studio worker: process whole buffers offline, one wasm instance per (model, sample rate).
const BLOCK = 2048;
let enginePromise = null;
const instances = new Map();
async function instanceFor(module, modelUrl, sampleRate) {
  const key = modelUrl + '@' + sampleRate;
  if (instances.has(key)) return instances.get(key);
  const response = await fetch(modelUrl);
  if (!response.ok) throw new Error('NAM model unavailable: ' + modelUrl);
  const json = await response.text();
  const id = module._nam_createInstance(sampleRate, BLOCK);
  const bytes = module.lengthBytesUTF8(json) + 1;
  const pointer = module._malloc(bytes);
  module.stringToUTF8(json, pointer, bytes);
  const ok = module._nam_loadModel(id, pointer, -1);
  module._free(pointer);
  if (!ok) throw new Error(module.UTF8ToString(module._nam_getLastError()) || 'model load failed');
  const entry = { id, buffer: module._nam_getBuffer(id) };
  instances.set(key, entry);
  return entry;
}
self.onmessage = async ({ data }) => {
  const { jobId, modelUrl, sampleRate, input } = data;
  try {
    enginePromise ??= createNamEngine();
    const module = await enginePromise;
    const { id, buffer } = await instanceFor(module, modelUrl, sampleRate);
    const output = new Float32Array(input.length);
    for (let offset = 0; offset < input.length; offset += BLOCK) {
      const frames = Math.min(BLOCK, input.length - offset);
      new Float32Array(module.HEAPF32.buffer, buffer, frames).set(input.subarray(offset, offset + frames));
      module._nam_process(id, frames);
      output.set(new Float32Array(module.HEAPF32.buffer, buffer, frames), offset);
    }
    self.postMessage({ jobId, output }, [output.buffer]);
  } catch (error) {
    self.postMessage({ jobId, error: error instanceof Error ? error.message : String(error) });
  }
};
`;
await writeFile(new URL('nam-worker.js', root), worker);
console.log(`nam-worker.js written (${worker.length} bytes)`);
